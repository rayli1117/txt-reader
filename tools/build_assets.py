"""Generate s2t.js (Simplified -> Traditional char map) and app icons for the reader PWA."""
import json
import os

import opencc
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "reader")
DICT_DIR = os.path.join(os.path.dirname(opencc.__file__), "dictionary")


def load_dict(name):
    m = {}
    with open(os.path.join(DICT_DIR, name), encoding="utf-8") as f:
        for line in f:
            parts = line.rstrip("\n").split("\t")
            if len(parts) >= 2:
                m[parts[0]] = parts[1].split(" ")[0]
    return m


def build_s2t():
    st_chars = load_dict("STCharacters.txt")
    st_phrases = load_dict("STPhrases.txt")
    tw_variants = {k: v for k, v in load_dict("TWVariants.txt").items() if len(k) == 1 and len(v) == 1}

    def tw(s):
        return "".join(tw_variants.get(c, c) for c in s)

    char_map = {}
    for s, t in st_chars.items():
        if len(s) == 1 and len(t) == 1:
            char_map[s] = tw(t)
    for s, t in tw_variants.items():
        char_map.setdefault(s, t)
    char_map = {s: t for s, t in char_map.items() if s != t}

    def char_conv(s):
        return "".join(char_map.get(c, c) for c in s)

    # Only keep phrases whose result differs from plain char-by-char conversion.
    phrases = {}
    for s, t in st_phrases.items():
        t = tw(t)
        if len(s) == len(t) and char_conv(s) != t:
            phrases[s] = t

    src = "".join(char_map.keys())
    dst = "".join(char_map.values())
    phrase_blob = "\n".join(f"{s}\t{t}" for s, t in sorted(phrases.items()))
    js = (
        "// Auto-generated by tools/build_assets.py from OpenCC (STCharacters, STPhrases, TWVariants)\n"
        f"window.S2T_SRC = {json.dumps(src, ensure_ascii=False)};\n"
        f"window.S2T_DST = {json.dumps(dst, ensure_ascii=False)};\n"
        f"window.S2T_PHRASES = {json.dumps(phrase_blob, ensure_ascii=False)};\n"
    )
    with open(os.path.join(OUT, "s2t.js"), "w", encoding="utf-8") as f:
        f.write(js)
    print(f"s2t.js: {len(char_map)} chars, {len(phrases)} phrases")


def build_icon(size):
    img = Image.new("RGB", (size, size), (44, 36, 30))
    d = ImageDraw.Draw(img)
    pad = size * 0.18
    d.rounded_rectangle(
        [pad, pad * 1.1, size - pad, size - pad * 0.9],
        radius=size * 0.06,
        fill=(242, 228, 201),
    )
    d.line([size / 2, pad * 1.1, size / 2, size - pad * 0.9], fill=(150, 120, 90), width=max(2, size // 60))
    font = None
    for name in ("msjh.ttc", "msyh.ttc", "simhei.ttf"):
        try:
            font = ImageFont.truetype(os.path.join(os.environ.get("WINDIR", "C:/Windows"), "Fonts", name), int(size * 0.3))
            break
        except OSError:
            continue
    if font:
        d.text((size / 2, size / 2), "讀", font=font, fill=(120, 40, 40), anchor="mm")
    img.save(os.path.join(OUT, f"icon-{size}.png"))


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    build_s2t()
    for s in (180, 192, 512):
        build_icon(s)
    print("icons done")
